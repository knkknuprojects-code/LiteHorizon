"""Structured analysis data model.

A horizon-scan over one text produces an :class:`Analysis`: a summary, the key
signals, a classification, extracted entities, keywords, and provenance. Frozen
dataclasses mirror the style of ``config.py``; enums keep the comparable fields
(maturity / impact / time horizon) stable across runs while ``theme`` stays an
open-ended, domain-agnostic string.

Serialization is plain dicts (``to_dict`` / ``from_dict``) so the store can write
JSON without any extra dependency.
"""

from __future__ import annotations

import hashlib
from dataclasses import asdict, dataclass
from enum import Enum


class Maturity(str, Enum):
    """How far along the development of a signal appears to be."""

    EMERGING = "emerging"
    GROWING = "growing"
    MATURE = "mature"
    DECLINING = "declining"


class Impact(str, Enum):
    """Rough magnitude of the signal's potential impact."""

    LOW = "low"
    MEDIUM = "medium"
    HIGH = "high"


class TimeHorizon(str, Enum):
    """When the signal is likely to matter."""

    NEAR = "near"
    MID = "mid"
    LONG = "long"


@dataclass(frozen=True)
class Classification:
    """Where a signal sits: open-ended theme plus comparable enum axes."""

    theme: str
    maturity: Maturity
    impact: Impact
    time_horizon: TimeHorizon


@dataclass(frozen=True)
class Entities:
    """Named things extracted from the text. Each list may be empty."""

    organizations: tuple[str, ...] = ()
    people: tuple[str, ...] = ()
    technologies: tuple[str, ...] = ()
    locations: tuple[str, ...] = ()


@dataclass(frozen=True)
class Analysis:
    """The full structured result of scanning one text."""

    summary: str
    signals: tuple[str, ...]
    classification: Classification
    entities: Entities
    keywords: tuple[str, ...]
    # Provenance — recorded with every analysis so results are reproducible and
    # the store can key/cache on (content_hash, prompt_version).
    content_hash: str
    model_id: str
    prompt_version: str
    strategy: str
    generated_at: str
    # When the item is dated for trend velocity. Defaults to generated_at (scan
    # time) until ingestion (Phase 5) brings real source/event dates.
    item_date: str
    # Training-data provenance (Phase 4). ``source`` labels where this record came
    # from — "model" (auto-generated by a scan, unvetted), "teacher" (a designated
    # teacher model for distillation), or "human" (hand-written/corrected).
    # ``approved`` gates a record into the curated training set: export can filter
    # to approved-only, and ``horizon approve`` flips it after review.
    source: str = "model"
    approved: bool = False
    # Ingestion provenance (Phase 5). A separate axis from ``source`` above: where
    # the *text* was gathered from, not how the *analysis* was produced. ``origin``
    # is the ingest source label (feed name / "local"); ``url`` is the item's link.
    # Empty/None for texts scanned directly (``horizon scan``) rather than gathered.
    origin: str = ""
    url: str | None = None
    # Attention signal (optional, adapter-supplied). A float in [0, 1] ranking this item
    # against its own comparable cohort — how much attention it drew relative to peers,
    # as the ingest adapter measures it (WoS/Scopus: the citation percentile within the
    # publication year; a future feed/repo adapter could use a different signal on the
    # same scale). Deliberately a normalized *rank*, so values stay commensurable across
    # adapters and eras where raw counts would not. ``None`` means **unknown**, not "no
    # attention": most sources give no signal at all, and 48.7% of the Scopus-only
    # bibliographic records carry no citation count. Set from
    # ``RawItem.meta[ATTENTION_KEY]`` when a gathered item is scanned; never
    # model-produced, so it is not part of the SFT target (``export.completion_dict``
    # whitelists the content fields).
    attention: float | None = None

    def to_dict(self) -> dict:
        """Return a JSON-serializable dict (enums become their string values)."""
        data = asdict(self)
        cls = data["classification"]
        cls["maturity"] = self.classification.maturity.value
        cls["impact"] = self.classification.impact.value
        cls["time_horizon"] = self.classification.time_horizon.value
        # tuples -> lists for clean JSON
        data["signals"] = list(self.signals)
        data["keywords"] = list(self.keywords)
        for key in ("organizations", "people", "technologies", "locations"):
            data["entities"][key] = list(getattr(self.entities, key))
        return data

    @classmethod
    def from_dict(cls, data: dict) -> "Analysis":
        """Rebuild an :class:`Analysis` from :meth:`to_dict` output."""
        c = data["classification"]
        classification = Classification(
            theme=c["theme"],
            maturity=Maturity(c["maturity"]),
            impact=Impact(c["impact"]),
            time_horizon=TimeHorizon(c["time_horizon"]),
        )
        e = data.get("entities", {})
        entities = Entities(
            organizations=tuple(e.get("organizations", [])),
            people=tuple(e.get("people", [])),
            technologies=tuple(e.get("technologies", [])),
            locations=tuple(e.get("locations", [])),
        )
        return cls(
            summary=data["summary"],
            signals=tuple(data["signals"]),
            classification=classification,
            entities=entities,
            keywords=tuple(data["keywords"]),
            content_hash=data["content_hash"],
            model_id=data["model_id"],
            prompt_version=data["prompt_version"],
            strategy=data["strategy"],
            generated_at=data["generated_at"],
            # Back-compat: pre-Phase-3 records have no item_date.
            item_date=data.get("item_date", data["generated_at"]),
            # Back-compat: pre-Phase-4 records have no provenance/approval — treat
            # them as unvetted model output.
            source=data.get("source", "model"),
            approved=bool(data.get("approved", False)),
            # Back-compat: pre-Phase-5 records have no ingestion provenance.
            origin=data.get("origin", ""),
            url=data.get("url"),
            # Back-compat: records scanned before the attention signal have none.
            attention=as_attention(data.get("attention")),
        )


def as_attention(value: object) -> float | None:
    """Coerce ``value`` to a valid :attr:`Analysis.attention`, or ``None``.

    Clamps to ``[0, 1]`` and rejects non-numerics, booleans and NaN. The invariant lives
    here, next to the field that declares it, so ingest and the store cannot disagree
    about what a valid attention value is.
    """
    if isinstance(value, bool) or not isinstance(value, (int, float)):
        return None
    number = float(value)
    if number != number:  # NaN
        return None
    return min(max(number, 0.0), 1.0)


def content_hash(text: str) -> str:
    """Stable sha256 over normalized text (used as the cache/provenance key)."""
    normalized = " ".join(text.split())
    return hashlib.sha256(normalized.encode("utf-8")).hexdigest()
